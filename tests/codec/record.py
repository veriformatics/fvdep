def ranges(values: list[int], width: int) -> str:
    def show(n: int) -> str:
        return str(n).zfill(width)
    runs: list[str] = []
    for _, group in itertools.groupby(enumerate(sorted(values)), key=lambda p: p[1] - p[0]):
        xs = [n for _, n in group]
        runs.append(show(xs[0]) if len(xs) == 1 else show(xs[0]) + ".." + show(xs[-1]))
    return "[" + ",".join(runs) + "]" if len(values) > 1 else show(values[0])


def compact(ids: list[str]) -> str:
    groups: dict[tuple[tuple[str, ...], tuple[int, ...]], list[tuple[tuple[int, ...], str]]] = {}
    for id in ids:
        digits = re.findall(r"\d+", id)
        shape = tuple(re.split(r"\d+", id))
        widths = tuple(len(d) if len(d) > 1 and d.startswith("0") else 0 for d in digits)
        key = (shape, widths)
        groups.setdefault(key, []).append((tuple(map(int, digits)), id))
    out: list[str] = []
    for (shape, widths), entries in groups.items():
        if not widths:
            out.append(entries[0][1])
            continue
        axes = [sorted({coords[i] for coords, _ in entries}) for i in range(len(widths))]
        if math.prod(map(len, axes)) != len(entries):
            out.extend(id for _, id in entries)
            continue
        result = shape[0]
        for values, width, suffix in zip(axes, widths, shape[1:], strict=True):
            result += ranges(values, width) + suffix
        out.append(result)
    return ";".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("log", type=Path)
    parser.add_argument("--column", default="stubA")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument("--command", default="tools/vflab-run bash tests/codec/run.sh")
    args = parser.parse_args()
    lines = args.log.read_text(encoding="utf-8").splitlines()
    verdicts: dict[str, tuple[bool, str]] = {}
    clauses: dict[str, tuple[str, list[str], list[str]]] = {}
    summary = [line for line in lines if line.startswith("SUMMARY ")]
    assert len(summary) == 1 and "driver_rc=0 " in summary[0], "completed clean-driver run required"
    assert not any("Traceback" in line or "driver-error:" in line for line in lines)
    for line in lines:
        match = re.match(r"^(PASS|FAIL) (\S+)(?: (.*))?$", line)
        if match:
            verdict, id, _ = match.groups()
            assert id not in verdicts
            verdicts[id] = (verdict == "PASS", line)
        match = re.match(r"^CLAUSE (\S+) (\d+F/\d+P) cases=(\S+) methods=(\S+)$", line)
        if match:
            id, count, cases, methods = match.groups()
            assert id not in clauses
            clauses[id] = (count, cases.split(","), methods.split(","))
    assert len(clauses) == 27 and set(clauses) == set(NOTES)
    expected_count = re.search(r" cases=(\d+) ", summary[0])
    assert expected_count is not None and int(expected_count.group(1)) == len(verdicts)
    table = args.root / "COVERAGE.tsv"
    with table.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream, delimiter="\t")
        fields = reader.fieldnames
        assert fields is not None
        headers = list(fields)
        rows = list(reader)
    assert len(rows) == 27 and {row["id"] for row in rows} == set(clauses)
    if args.column not in headers:
        headers.append(args.column)
    for row in rows:
        count, cases, methods = clauses[row["id"]]
        p = sum(verdicts[id][0] for id in cases)
        assert count == f"{len(cases) - p}F/{p}P"
        row["cases"] = compact(cases)
        method = ";".join(methods)
        if row["id"].startswith(("J2-", "J3-")) or row["id"] in ["J1-valid", "J-oracle"]:
            method += ";differential(independent J2/J3)"
        if row["id"] == "J4-jq":
            method += ";differential(jq -S -c)"
        if row["id"] in ["H2-frame", "H2-unframe-ok", "H2-unframe-refuse", "H3-argv", "H3-adapter"]:
            method += ";differential(independent H2/H3)"
        row["method"] = method
        row[args.column] = count
        row["notes"] = NOTES[row["id"]]
    with table.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, headers, delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    with (args.root / f"RESULTS.{args.column}.tsv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream, delimiter="\t", lineterminator="\n")
        writer.writerow(["id", "command", "output"])
        writer.writerows((id, args.command, line) for id, (_, line) in verdicts.items())
    with (args.root / f"GREEN.{args.column}.txt").open("w", encoding="utf-8") as stream:
        stream.writelines(id + "\n" for id, (passed, _) in verdicts.items() if passed)
    print(f"RECORDED {args.column} rows=27 cases={len(verdicts)} pass={sum(v[0] for v in verdicts.values())}")
    print(summary[0])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
